"""Generate original surface and bounded-fog scenes with angular patterned lights."""
import argparse
import math
from pathlib import Path
import struct
import zlib

from generate_spot_samples import box, diffuse, floor_and_back, header, sphere


def angular_png():
    """Owned grayscale PNG: broad downward lobe cut into six angular petals.

    Invert the equal-area square map analytically, then evaluate an authored
    directional function. Default PBRT Y/Z exchange makes native -Z world -Y.
    Grayscale samples deliberately retain their native encoded values.
    """
    n = 256
    rows = []
    for iy in range(n):
        row = bytearray()
        for ix in range(n):
            u, v = 2 * (ix + .5) / n - 1, 2 * (iy + .5) / n - 1
            distance = 1 - abs(u) - abs(v)
            radius = 1 - abs(distance)
            phi = math.pi / 4 * ((abs(v) - abs(u)) / radius + 1) if radius else 0
            z = math.copysign(1 - radius * radius, distance)
            azimuth = math.atan2(math.copysign(math.sin(phi), v),
                                 math.copysign(math.cos(phi), u))
            angle = math.acos(max(-1., min(1., -z)))
            aperture = max(0., min(1., (math.radians(48) - angle) / math.radians(7)))
            petals = max(0., math.cos(3 * azimuth + 2.4 * angle)) ** 8
            center = math.exp(-((angle / .085) ** 2))
            value = aperture * (.008 + .992 * max(petals, center))
            row.append(round(255 * value))
        rows.append(b'\0' + row)

    def chunk(kind, payload):
        return (struct.pack('>I', len(payload)) + kind + payload +
                struct.pack('>I', zlib.crc32(kind + payload) & 0xffffffff))

    return (b'\x89PNG\r\n\x1a\n' +
            chunk(b'IHDR', struct.pack('>IIBBBBB', n, n, 8, 0, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(b''.join(rows))) + chunk(b'IEND', b''))


def light(position, rgb, power, rotation=0):
    return f'''AttributeBegin
Translate {' '.join(map(str, position))}
Rotate {rotation} 0 0 1
LightSource "goniometric" "string filename" ["angular-petals.png"]
 "rgb I" [{' '.join(map(str, rgb))}] "float power" [{power}]
AttributeEnd
'''


def generate(destination, samples=512, width=768, height=512):
    destination.mkdir(parents=True, exist_ok=True)
    (destination/'angular-petals.png').write_bytes(angular_png())
    def scene_header(integrator):
        return header((8.2, 6.8, -10), (0, .8, 2.5), integrator, samples, width, height).replace(
            'spotlight sample; generated by generate_spot_samples.py',
            'goniometric sample; generated by generate_goniometric_samples.py')
    lights = light((-2.6, 5.5, 2.2), (1, .3, .06), 200, -10)
    lights += light((2.8, 5.8, 3.8), (.04, .55, 1), 230, 12)
    surface = scene_header('path') + 'LightSource "infinite" "float scale" [.018]\n' + lights
    surface += floor_and_back()
    surface += diffuse((.5, .52, .56)) + box((-.3, -.05, 3.8), (.3, 1.8, 4.4))
    surface += 'Material "conductor" "rgb reflectance" [.72 .58 .35] "float roughness" [.23] "bool remaproughness" [false]\n'
    surface += sphere((0, .75, 1.5), .75)
    (destination/'angular-studio.pbrt').write_text(surface)
    fog = scene_header('volpath')
    fog += 'MakeNamedMedium "haze" "string type" "homogeneous" "spectrum sigma_a" [360 .012 830 .012] "spectrum sigma_s" [360 .12 830 .12] "float g" [.2]\n'
    fog += 'AttributeBegin\nMaterial "interface"\nMediumInterface "haze" ""\n'
    fog += box((-6, 0, -2), (6, 6.5, 9)) + 'AttributeEnd\n' + lights
    fog += 'LightSource "infinite" "float scale" [.005]\n' + floor_and_back()
    fog += diffuse((.2, .22, .25)) + box((-.6, -.05, 3.2), (.6, .3, 4.4))
    (destination/'angular-fog.pbrt').write_text(fog)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, default=Path(__file__).resolve().parents[1]/'build/goniometric-samples')
    parser.add_argument('--samples', type=int, default=512)
    parser.add_argument('--width', type=int, default=768)
    parser.add_argument('--height', type=int, default=512)
    args = parser.parse_args()
    if not 1 <= args.samples <= 1048576 or args.samples & (args.samples - 1):
        parser.error('--samples must be a power of two from 1 through 1048576')
    if not 1 <= args.width <= 4096 or not 1 <= args.height <= 4096:
        parser.error('--width and --height must be from 1 through 4096')
    generate(args.output_dir.resolve(), args.samples, args.width, args.height)
    print('Generated angular-studio.pbrt, angular-fog.pbrt and angular-petals.png')


if __name__ == '__main__':
    main()
