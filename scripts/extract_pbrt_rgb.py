"""Extract the canonical sRGB and normalized D65 data from pinned PBRT v4."""

import argparse
import hashlib
import re
import struct
import subprocess
from pathlib import Path

REVISION = "b0bdf461ba5dd6504b70ebf0932acc0fe7aa744f"
GENERATED_SRGB_SHA256 = "adc5a39d555761307987b8b307b607fd848415edd85263f3635c28b0c7236102"
SRGB_SHA256 = "6adffc41eefcf064b6524606cb8734941aa69ac962ac268fd9276f440cef61d5"
D65_SHA256 = "5a9a9c41d16cd61a936704cd5194ec0d2ade4f5f64c728419e2befaac566006a"
FLOAT_PATTERN = r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?"


def array(source, name):
    match = re.search(rf"\b{name}(?:\[[^\]]*\])+\s*=\s*\{{(.*?)\}};", source, re.S)
    if match is None:
        raise ValueError(f"PBRT array {name} is missing")
    return [float(value) for value in re.findall(FLOAT_PATTERN, match[1])]


def verify(data, expected, name):
    digest = hashlib.sha256(data).hexdigest()
    if digest != expected:
        raise ValueError(f"Unexpected {name} SHA-256: {digest}")


def extract_srgb(generated):
    verify(generated, GENERATED_SRGB_SHA256, "generated PBRT sRGB source")
    source = generated.decode("ascii")
    nodes = array(source, "sRGBToSpectrumTable_Scale")
    coefficients = array(source, "sRGBToSpectrumTable_Data")
    if len(nodes) != 64 or len(coefficients) != 3 * 64**3 * 3:
        raise ValueError("Unexpected PBRT sRGB table dimensions")
    data = struct.pack(f"<{len(nodes) + len(coefficients)}f", *nodes, *coefficients)
    verify(data, SRGB_SHA256, "extracted sRGB table")
    return data


def f32(value):
    return struct.unpack("<f", struct.pack("<f", value))[0]


def lerp(t, a, b):
    return f32(f32(f32(1.0 - t) * a) + f32(t * b))


def interpolate_d65(knots, wavelength):
    # At the last knot PBRT interpolates from the preceding interval.
    index = min((wavelength - 300) // 5, len(knots) - 2)
    t = f32((wavelength - (300 + 5 * index)) / 5)
    return lerp(t, knots[index], knots[index + 1])


def extract_d65(spectrum, header):
    wavelengths = range(360, 831)
    if array(spectrum, "CIE_lambda") != list(wavelengths):
        raise ValueError("Unexpected PBRT CIE sampling grid")
    cie_y = array(spectrum, "CIE_Y")
    interleaved = array(spectrum, "CIE_Illum_D6500")
    if interleaved[::2] != list(range(300, 831, 5)) or len(cie_y) != len(wavelengths):
        raise ValueError("Unexpected PBRT D65 or CIE Y data")
    integral = re.search(rf"\bCIE_Y_integral = ({FLOAT_PATTERN});", header)
    if integral is None:
        raise ValueError("PBRT CIE Y integral is missing")

    # Match the upstream Float accumulation and Scale of the 5 nm knots,
    # followed by interpolation at the 1 nm sample wavelengths.
    knots = [f32(value) for value in interleaved[1::2]]
    photometric = 0.0
    for wavelength, y in zip(wavelengths, cie_y):
        photometric = f32(photometric + f32(interpolate_d65(knots, wavelength) * f32(y)))
    scale = f32(f32(float(integral[1])) / photometric)
    knots = [f32(value * scale) for value in knots]
    values = [interpolate_d65(knots, wavelength) for wavelength in wavelengths]

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// pbrt is Copyright(c) 1998-2020 Matt Pharr, Wenzel Jakob, and Greg Humphreys.",
        "// PhysLight code contributed by Anders Langlands and Luca Fascione",
        "// Copyright (c) 2020, Weta Digital, Ltd.",
        "// Normalized PBRT stdillum-D65 at integer wavelengths 360–830 nm.",
        "// Generated by scripts/extract_pbrt_rgb.py. See third_party/pbrt/README.md.",
    ]
    literals = [f"{value.hex()}f" for value in values]
    lines.extend("    " + ", ".join(literals[i : i + 4]) + "," for i in range(0, len(values), 4))
    return "\n".join(lines) + "\n"


def read_pinned(source, name):
    return subprocess.check_output(
        ["git", "-C", source, "show", f"{REVISION}:src/pbrt/util/{name}"], text=True
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pbrt_source", type=Path, help="PBRT Git checkout containing the pinned revision")
    parser.add_argument("generated_srgb", type=Path, help="pinned rgbspectrum_srgb.cpp")
    parser.add_argument("output_directory", type=Path)
    args = parser.parse_args()

    srgb = extract_srgb(args.generated_srgb.read_bytes())
    d65 = extract_d65(
        read_pinned(args.pbrt_source, "spectrum.cpp"), read_pinned(args.pbrt_source, "spectrum.h")
    ).encode("utf-8")
    verify(d65, D65_SHA256, "extracted D65 table")
    args.output_directory.mkdir(parents=True, exist_ok=True)
    (args.output_directory / "srgb.bin").write_bytes(srgb)
    (args.output_directory / "d65.inc").write_bytes(d65)


if __name__ == "__main__":
    main()
