"""Generate original scenes contrasting equal radiance and per-primitive power."""
import argparse
from pathlib import Path
from generate_spot_samples import box, diffuse, header, mesh


def panel(x, halfwidth, power):
    """Each square has exactly two equal-area triangles, facing the floor."""
    y, z = 3.8, 2.2
    p = [(x-halfwidth,y,z-halfwidth), (x+halfwidth,y,z-halfwidth),
         (x+halfwidth,y,z+halfwidth), (x-halfwidth,y,z+halfwidth)]
    emission = '"float power" [1.00530965]' if power else ''
    return ('AttributeBegin\nMaterial "diffuse" "rgb reflectance" [0 0 0]\n'
            'AreaLightSource "diffuse" "blackbody L" [4800] "float scale" [18] '+emission+'\n'+
            mesh(p, [(0,1,2),(0,2,3)])+'AttributeEnd\n')


def generate(destination, samples=512, width=768, height=512):
    destination.mkdir(parents=True, exist_ok=True)
    for name, power in [('constant-radiance', False), ('equal-primitive-power', True)]:
        s = header((7,5.4,-10), (0,1.5,2.4), 'path', samples, width, height).replace(
            'spotlight sample; generated by generate_spot_samples.py',
            'area-power sample; generated by generate_area_power_samples.py')
        s += '# Left: 0.8m panel, right: 2.4m panel; exactly two triangles each.\n'
        s += panel(-2.4,.4,power)+panel(2.4,1.2,power)
        s += diffuse((.55,.57,.60))+box((-6,-.15,-2),(6,0,6.5))
        s += diffuse((.36,.40,.46))+box((-6,0,6),(6,4.8,6.12))
        # Low central divider separates pools without occluding the emitter view.
        s += diffuse((.12,.15,.20))+box((-.1,0,-.3),(.1,.9,5.8))
        for x in (-2.4,2.4):
            s += diffuse((.15,.17,.20))+box((x-.9,0,1.3),(x+.9,.18,3.1))
            s += diffuse((.65,.12,.055))+box((x-.65,.18,1.6),(x-.1,1.3,2.15))
            s += diffuse((.045,.34,.48))+box((x+.12,.18,2.25),(x+.65,.85,2.9))
            s += diffuse((.66,.54,.23))+mesh([(x-.4,.18,3.6),(x+.45,.18,3.6),
                (x+.45,.18,4.25),(x-.4,.18,4.25),(x,.95,3.9)],
                [(0,1,4),(1,2,4),(2,3,4),(3,0,4),(0,3,2),(0,2,1)])
        (destination/(name+'.pbrt')).write_text(s)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir',type=Path,default=Path('build/area-power-samples'))
    parser.add_argument('--samples',type=int,default=512)
    parser.add_argument('--width',type=int,default=768)
    parser.add_argument('--height',type=int,default=512)
    args=parser.parse_args()
    if not 1 <= args.samples <= 1048576 or args.samples & (args.samples-1):
        parser.error('--samples must be a power of two from 1 through 1048576')
    if not 1 <= args.width <= 4096 or not 1 <= args.height <= 4096:
        parser.error('--width and --height must be from 1 through 4096')
    generate(args.output_dir.resolve(),args.samples,args.width,args.height)
    print('Generated constant-radiance.pbrt and equal-primitive-power.pbrt')


if __name__ == '__main__':
    main()
