"""Generate original surface and fog scenes demonstrating spectral spot lighting."""
import argparse
import math
from pathlib import Path

def mesh(points, faces, normals=None):
    f = lambda x: f'{x:.8g}'
    text = 'Shape "trianglemesh" "point3 P" [' + ' '.join((f(v) for p in points for v in p)) + ']\n'
    if normals:
        text += ' "normal N" [' + ' '.join((f(v) for n in normals for v in n)) + ']\n'
    return text + ' "integer indices" [' + ' '.join((str(i) for t in faces for i in t)) + ']\n'

def box(lo, hi):
    x, y, z = lo
    X, Y, Z = hi
    p = [(x, y, z), (X, y, z), (X, Y, z), (x, Y, z), (x, y, Z), (X, y, Z), (X, Y, Z), (x, Y, Z)]
    faces = []
    for a, b, c, d in [(0, 3, 2, 1), (4, 5, 6, 7), (0, 4, 7, 3), (1, 2, 6, 5), (0, 1, 5, 4), (3, 7, 6, 2)]:
        faces.extend([(a, b, c), (a, c, d)])
    return mesh(p, faces)

def sphere(center, radius):
    nlat, nlon = (24, 48)
    points = []
    normals = []
    for i in range(nlat + 1):
        t = math.pi * i / nlat
        for j in range(nlon):
            a = 2 * math.pi * j / nlon
            n = (math.sin(t) * math.cos(a), math.cos(t), math.sin(t) * math.sin(a))
            normals.append(n)
            points.append(tuple((center[k] + radius * n[k] for k in range(3))))
    faces = []
    for i in range(nlat):
        for j in range(nlon):
            a = i * nlon + j
            b = i * nlon + (j + 1) % nlon
            c = (i + 1) * nlon + j
            d = (i + 1) * nlon + (j + 1) % nlon
            if i > 0:
                faces.append((a, b, c))
            if i < nlat - 1:
                faces.append((b, d, c))
    return mesh(points, faces, normals)

def header(eye, target, integrator, samples, width, height):
    return f'''# Original rypath spotlight sample; generated by generate_spot_samples.py; no external assets.\nLookAt {' '.join(map(str, eye))} {' '.join(map(str, target))} 0 1 0\nCamera "perspective" "float fov" [39]\nFilm "rgb" "integer xresolution" [{width}] "integer yresolution" [{height}]\n "string sensor" "cie1931" "float iso" [100] "bool savefp16" [false]\nPixelFilter "triangle" "float xradius" [1] "float yradius" [1]\nSampler "sobol" "integer pixelsamples" [{samples}] "integer seed" [17]\nIntegrator "{integrator}" "integer maxdepth" [6]\nWorldBegin\n'''

def spot(pos, target, rgb, power, cone, delta):
    return f"""LightSource "spot" "point3 from" [{' '.join(map(str, pos))}]\n "point3 to" [{' '.join(map(str, target))}] "rgb I" [{' '.join(map(str, rgb))}]\n "float power" [{power}] "float coneangle" [{cone}] "float conedeltaangle" [{delta}]\n"""

def diffuse(rgb):
    return 'Material "diffuse" "rgb reflectance" [' + ' '.join(map(str, rgb)) + ']\n'

def floor_and_back():
    return diffuse((0.25, 0.28, 0.32)) + box((-9, -0.12, -5), (9, -0.06, 12)) + diffuse((0.055, 0.065, 0.09)) + box((-9, -0.06, 8), (9, 8, 8.1))

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path,
                        default=Path(__file__).resolve().parents[1] / 'build/spot-samples')
    parser.add_argument('--samples', type=int, default=512)
    parser.add_argument('--width', type=int, default=768)
    parser.add_argument('--height', type=int, default=512)
    args = parser.parse_args()
    if not 1 <= args.samples <= 1048576 or args.samples & (args.samples - 1):
        parser.error('--samples must be a power of two from 1 through 1048576')
    if not 1 <= args.width <= 4096 or not 1 <= args.height <= 4096:
        parser.error('--width and --height must be from 1 through 4096')
    destination = args.output_dir.resolve()
    destination.mkdir(parents=True, exist_ok=True)
    s = header((7, 4.2, -9), (0, 1.0, 2), 'path', args.samples, args.width, args.height)
    s += 'LightSource "infinite" "float scale" [.07]\n'
    s += spot((-3.4, 5.5, -0.3), (-1.4, 0, 2.2), (1, 0.34, 0.07), 48, 30, 14)
    s += spot((4, 4.8, 1.3), (1.4, 0, 2.7), (0.06, 0.65, 1), 58, 29, 15)
    s += spot((0, 5, 5), (0, 1, 2.3), (1, 0.9, 0.74), 8, 22, 9)
    s += floor_and_back()
    s += diffuse((0.12, 0.13, 0.16)) + box((-2.6, -0.05, 1), (-0.6, 0.32, 3))
    s += diffuse((0.12, 0.13, 0.16)) + box((0.65, -0.05, 2.1), (2.45, 0.55, 3.9))
    s += 'Material "coateddiffuse" "rgb reflectance" [.66 .69 .74] "float roughness" [.16] "float thickness" [.02]\n'
    s += sphere((-1.6, 1.22, 2), 0.9)
    s += 'Material "conductor" "rgb reflectance" [.75 .58 .32] "float roughness" [.2] "bool remaproughness" [false]\n'
    s += sphere((1.55, 1.25, 3), 0.7)
    s += diffuse((0.45, 0.49, 0.57)) + box((-0.35, -0.05, 4.1), (0.45, 1.9, 4.9))
    (destination / 'chromatic-studio.pbrt').write_text(s)
    s = 'MakeNamedMedium "haze" "string type" "homogeneous" "spectrum sigma_a" [360 .018 830 .018] "spectrum sigma_s" [360 .16 830 .16] "float g" [.2]\nMediumInterface "" "haze"\n'
    s += header((7.7, 3.6, -9), (0, 2.0, 2.5), 'volpath', args.samples, args.width, args.height)
    s += spot((-3.5, 5.1, 0.3), (0.1, 0.1, 3.6), (1, 0.34, 0.08), 40, 16, 7)
    s += spot((3.6, 4.9, 4), (-1.2, 0.1, 1.5), (0.07, 0.56, 1), 48, 18, 8)
    (destination / 'crossed-fog-beams.pbrt').write_text(s)
    print('Generated chromatic-studio.pbrt and crossed-fog-beams.pbrt')


if __name__ == '__main__':
    main()
